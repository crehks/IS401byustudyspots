-- Local-only fixture for the dev page. Mimics the Supabase pieces the admin gate relies on
-- (roles, auth schema, auth.uid()/auth.jwt()) plus a trimmed copy of the real public tables.
create role anon nologin;
create role authenticated nologin;
create schema if not exists auth;
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table auth.users (
  id uuid primary key default gen_random_uuid(),
  email text unique not null,
  encrypted_password text not null,
  raw_app_meta_data jsonb not null default '{}'::jsonb,
  email_confirmed_at timestamptz,
  banned_until timestamptz,
  last_sign_in_at timestamptz,
  created_at timestamptz not null default now()
);

create function auth.jwt() returns jsonb language sql stable as
  $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
create function auth.uid() returns uuid language sql stable as
  $$ select nullif(auth.jwt() ->> 'sub', '')::uuid $$;

grant usage on schema public, auth to anon, authenticated;
-- Like Supabase: new public tables are granted to the API roles; RLS is what restricts them.
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
grant execute on function auth.jwt(), auth.uid() to anon, authenticated;

create table public."Buildings" (
  building_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  building_location text,
  opening_hrs time,
  closing_hrs time,
  building_name text,
  reservation_url text
);
create table public."Floors" (
  floor_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  floor_number bigint,
  building_id bigint references public."Buildings"(building_id)
);
create table public."SpotType" (
  spot_type_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  type_name text
);
create table public."StudySpot" (
  spot_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  spot_type_id bigint references public."SpotType"(spot_type_id),
  building_id bigint references public."Buildings"(building_id),
  floor_id bigint references public."Floors"(floor_id),
  outlets boolean,
  capacity bigint,
  spot_location text,
  reservable boolean,
  group_type text
);
create table public."ResourceType" (
  resource_type_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  resource_name text
);
create table public."Resources" (
  resource_id bigint generated by default as identity primary key,
  resource_type_id bigint references public."ResourceType"(resource_type_id),
  created_at timestamptz not null default now(),
  floor_id bigint references public."Floors"(floor_id),
  resource_info text,
  building_id bigint references public."Buildings"(building_id),
  resource_location text
);
create table public."BuildingHours" (
  hours_id bigint generated always as identity primary key,
  building_id bigint not null references public."Buildings"(building_id),
  day_of_week smallint check (day_of_week between 0 and 6),
  special_date date,
  open_time time,
  close_time time,
  is_closed boolean not null default false,
  note text
);

alter table public."Buildings" enable row level security;
alter table public."Floors" enable row level security;
alter table public."SpotType" enable row level security;
alter table public."StudySpot" enable row level security;
alter table public."ResourceType" enable row level security;
alter table public."Resources" enable row level security;
alter table public."BuildingHours" enable row level security;

grant select, insert, update, delete on all tables in schema public to anon, authenticated;
grant usage on all sequences in schema public to anon, authenticated;
