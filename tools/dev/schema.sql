-- Local-only fixture for the dev page. Mimics the Supabase pieces the admin gate relies on
-- (roles, auth schema, auth.uid()/auth.jwt()) plus a trimmed copy of the real public tables.
create role anon nologin;
create role authenticated nologin;
create schema if not exists auth;
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table auth.users (
  id uuid primary key default gen_random_uuid(),
  email text unique not null,
  encrypted_password text not null,
  raw_app_meta_data jsonb not null default '{}'::jsonb,
  email_confirmed_at timestamptz,
  banned_until timestamptz,
  last_sign_in_at timestamptz,
  created_at timestamptz not null default now()
);

create function auth.jwt() returns jsonb language sql stable as
  $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
create function auth.uid() returns uuid language sql stable as
  $$ select nullif(auth.jwt() ->> 'sub', '')::uuid $$;

grant usage on schema public, auth to anon, authenticated;
-- Like Supabase: new public tables are granted to the API roles; RLS is what restricts them.
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
grant execute on function auth.jwt(), auth.uid() to anon, authenticated;

create table public."Buildings" (
  building_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  building_location text,
  opening_hrs time,
  closing_hrs time,
  building_name text,
  reservation_url text
);
create table public."Floors" (
  floor_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  floor_number bigint,
  building_id bigint references public."Buildings"(building_id)
);
create table public."SpotType" (
  spot_type_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  type_name text
);
create table public."StudySpot" (
  spot_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  spot_type_id bigint references public."SpotType"(spot_type_id),
  building_id bigint references public."Buildings"(building_id),
  floor_id bigint references public."Floors"(floor_id),
  outlets boolean,
  capacity bigint,
  spot_location text,
  reservable boolean,
  group_type text
);
create table public."ResourceType" (
  resource_type_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  resource_name text
);
create table public."Resources" (
  resource_id bigint generated by default as identity primary key,
  resource_type_id bigint references public."ResourceType"(resource_type_id),
  created_at timestamptz not null default now(),
  floor_id bigint references public."Floors"(floor_id),
  resource_info text,
  building_id bigint references public."Buildings"(building_id),
  resource_location text
);
create table public."BuildingHours" (
  hours_id bigint generated always as identity primary key,
  building_id bigint not null references public."Buildings"(building_id),
  day_of_week smallint check (day_of_week between 0 and 6),
  special_date date,
  open_time time,
  close_time time,
  is_closed boolean not null default false,
  note text
);

alter table public."Buildings" enable row level security;
alter table public."Floors" enable row level security;
alter table public."SpotType" enable row level security;
alter table public."StudySpot" enable row level security;
alter table public."ResourceType" enable row level security;
alter table public."Resources" enable row level security;
alter table public."BuildingHours" enable row level security;

-- Mirrors the live project: spots are publicly readable (policy name matches live).
create policy studybyu_read_spots on public."StudySpot" for select to anon, authenticated using (true);
create policy studybyu_read_buildings on public."Buildings" for select to anon, authenticated using (true);
create policy studybyu_read_hours on public."BuildingHours" for select to anon, authenticated using (true);

-- Main-site sign-in looks up a linked profile row; reports start empty.
create table public."User" (
  user_id bigint generated by default as identity primary key,
  auth_id uuid unique,
  first_name text,
  last_name text
);
alter table public."User" enable row level security;
create policy user_own_row on public."User" for select to authenticated using (auth_id = auth.uid());

create type public.report_level as enum ('low', 'medium', 'high');
create table public."SpotSubmission" (
  submission_id bigint generated by default as identity primary key,
  spot_name text not null default 'sample',
  noise_level smallint not null check (noise_level >= 1 and noise_level <= 3)
);
create table public.spot_reports (
  id bigint generated always as identity primary key,
  space_id bigint not null,
  body text not null default 'sample',
  self_noise public.report_level,
  self_crowd public.report_level,
  noise_level public.report_level,
  crowd_level public.report_level
);
alter table public."SpotSubmission" enable row level security;
alter table public.spot_reports enable row level security;
create table public."ReportSpotStatus" (
  report_id bigint generated by default as identity primary key,
  spot_id bigint not null,
  user_id bigint,
  noise_level smallint,
  crowd_level smallint,
  notes text,
  created_at timestamptz not null default now()
);
alter table public."ReportSpotStatus" enable row level security;
-- Mirror the live report policies exactly as they were before the dev portal (migration 006 replaces them).
create policy studybyu_read_reports on public."ReportSpotStatus" for select to anon, authenticated
  using ((spot_id >= 1001) and (spot_id <= 1025));
create policy studybyu_submit_report_guest on public."ReportSpotStatus" for insert to anon
  with check ((user_id = 1001) and ((spot_id >= 1001) and (spot_id <= 1025)) and (exists (
    select 1 from public."StudySpot" s where ((s.spot_id = "ReportSpotStatus".spot_id) and (s.reservable = false)))));
create policy studybyu_submit_report_user on public."ReportSpotStatus" for insert to authenticated
  with check (((user_id = 1001) or (user_id in (select u.user_id from public."User" u where (u.auth_id = (select auth.uid() as uid)))))
    and ((spot_id >= 1001) and (spot_id <= 1025)) and (exists (
    select 1 from public."StudySpot" s where ((s.spot_id = "ReportSpotStatus".spot_id) and (s.reservable = false)))));

create view public.latest_report_spot_status with (security_invoker = true) as
  select distinct on (spot_id) report_id, created_at, spot_id, user_id, noise_level, crowd_level, notes
  from public."ReportSpotStatus" where spot_id >= 1001 and spot_id <= 1025
  order by spot_id, created_at desc, report_id desc;

grant select, insert, update, delete on all tables in schema public to anon, authenticated;

-- Mirror live privileges before the dev portal: spots and buildings are read-only for the API roles,
-- floors and spot types are not exposed at all. Migration 006 grants what the admin portal needs.
revoke insert, update, delete on public."Buildings", public."StudySpot" from anon, authenticated;
revoke all on public."Floors", public."SpotType" from anon, authenticated;
grant usage on all sequences in schema public to anon, authenticated;
