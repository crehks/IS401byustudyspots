-- "Report a new spot" submissions. Rows wait here (status = 'pending') until the team
-- decides whether approved submissions become Study Spot rows. Nothing here changes the
-- public catalogue. Public clients may INSERT limited columns but cannot read, edit, or delete.
create table if not exists public."SpotSubmission" (
  submission_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id bigint not null default 1001 references public."User"(user_id),
  building_id bigint not null references public."Buildings"(building_id),
  floor_number smallint,
  floor_label text not null check (char_length(floor_label) between 1 and 60),
  spot_name text not null check (char_length(spot_name) between 3 and 60),
  spot_type_id bigint not null references public."SpotType"(spot_type_id),
  capacity smallint not null default 1 check (capacity between 1 and 8),
  noise_level smallint not null check (noise_level between 1 and 3),
  outlets boolean not null default false,
  is_private boolean not null default false,
  location_details text check (char_length(location_details) <= 160),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  approved_spot_id bigint references public."StudySpot"(spot_id)
);

create index if not exists spotsubmission_user_idx on public."SpotSubmission"(user_id);
create index if not exists spotsubmission_building_idx on public."SpotSubmission"(building_id);
create index if not exists spotsubmission_type_idx on public."SpotSubmission"(spot_type_id);
create index if not exists spotsubmission_spot_idx on public."SpotSubmission"(approved_spot_id);

alter table public."SpotSubmission" enable row level security;

revoke all on public."SpotSubmission" from anon, authenticated;
grant insert (building_id, floor_number, floor_label, spot_name, spot_type_id, capacity,
              noise_level, outlets, is_private, location_details)
  on public."SpotSubmission" to anon, authenticated;

drop policy if exists studybyu_submit_spot on public."SpotSubmission";
create policy studybyu_submit_spot on public."SpotSubmission"
  for insert to anon, authenticated
  with check (user_id = 1001 and status = 'pending' and approved_spot_id is null
              and building_id in (1001, 1002, 1003) and spot_type_id in (1001, 1002, 1003));
